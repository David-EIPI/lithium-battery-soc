inline static
uint16_t voltage_to_soc(uint16_t voltage)
{
    unsigned i;
    unsigned table_len = sizeof(SOC_TABLE) / sizeof(SOC_TABLE[0]);
    uint16_t res = table_len;

    for (i = 0; i < table_len; i++) {
        if (voltage < SOC_TABLE[i]) {
            res = i;
            break;
        }
    }

    if (res == table_len) {
        return 100 * PERCENTAGE_MULTIPLIER;
    }

    if (0 == res) {
        return 0;
    }

    unsigned v1 = SOC_TABLE[res - 1];
    unsigned v2 = SOC_TABLE[res];
    unsigned tbl_step = PERCENTAGE_MULTIPLIER * 100 / (table_len - 1);

    unsigned dv = v2 - v1;

    unsigned interp = (i - 1) * tbl_step + (tbl_step * (voltage - v1) + dv / 2) / dv;

    return interp;
}

